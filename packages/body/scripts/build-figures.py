#!/usr/bin/env python3
"""Builds src/figures.ts, the realistic body, from MakeHuman's base mesh.

MakeHuman's base mesh and its targets were released as CC0 (public domain) in
September 2020: https://github.com/makehumancommunity/makehuman, LICENSE.ASSETS.md.
This keeps the body itself (no eyes, teeth or other helpers), applies the
young-adult male or female shape the way MakeHuman's defaults do (an even mix
of its three regional variants), and writes it small:

- positions as 16-bit integers, 1/15000 m apart (a fifteenth of a millimetre);
- the female figure as differences from the male, which compress well;
- faces as quads (MakeHuman's own), split into triangles in the browser;
- the joints, from MakeHuman's joint helpers, for placing the muscles.

The figure faces +z, its left side at +x, feet at y = 0, in metres.

To rebuild, fetch the few files it reads (about 10 MB), then run it:

    git clone --depth 1 --filter=blob:none --sparse https://github.com/makehumancommunity/makehuman mh
    git -C mh sparse-checkout set --no-cone /makehuman/data/3dobjs/base.obj '/makehuman/data/targets/macrodetails/*-young.target'
    python3 packages/body/scripts/build-figures.py mh/makehuman/data packages/body/src/figures.ts
"""

import base64
import struct
import sys
from pathlib import Path

SCALE = 15000  # integer steps per metre
REGIONS = ("african", "asian", "caucasian")
# MakeHuman's joint helpers (left side; the figure is symmetric) and our names for them.
JOINTS = {
    "head": "joint-head",
    "crown": "joint-head-2",
    "neck": "joint-neck",
    "clavicle": "joint-l-clavicle",
    "scapula": "joint-l-scapula",
    "shoulder": "joint-l-shoulder",
    "elbow": "joint-l-elbow",
    "wrist": "joint-l-hand",
    "chest": "joint-spine-1",
    "waist": "joint-spine-2",
    "belly": "joint-spine-3",
    "lowback": "joint-spine-4",
    "pelvis": "joint-pelvis",
    "hip": "joint-l-upper-leg",
    "knee": "joint-l-knee",
    "ankle": "joint-l-ankle",
    "toe": "joint-l-foot-1",
}


def read_mesh(data: Path):
    verts, quads, groups, group = [], [], {}, None
    for line in open(data / "3dobjs/base.obj"):
        if line.startswith("v "):
            verts.append([float(x) for x in line.split()[1:4]])
        elif line.startswith("g "):
            group = line.split(None, 1)[1].strip()
        elif line.startswith("f "):
            face = [int(token.split("/")[0]) - 1 for token in line.split()[1:]]
            groups.setdefault(group, set()).update(face)
            if group == "body":
                assert len(face) == 4, "the body is all quads"
                quads.append(face)
    return verts, quads, groups


def shaped(verts, data: Path, sex: str):
    """The base mesh with the young-adult targets for one sex applied, evenly mixed."""
    out = [list(v) for v in verts]
    for region in REGIONS:
        for line in open(data / f"targets/macrodetails/{region}-{sex}-young.target"):
            if not line.strip() or line.startswith("#"):
                continue
            i, dx, dy, dz = line.split()
            v = out[int(i)]
            v[0] += float(dx) / 3
            v[1] += float(dy) / 3
            v[2] += float(dz) / 3
    return out


def main(data: Path, target: Path):
    verts, quads, groups = read_mesh(data)
    used = sorted({i for quad in quads for i in quad})
    index = {old: new for new, old in enumerate(used)}
    assert len(used) < 65536

    figures = {}
    for sex in ("male", "female"):
        v = shaped(verts, data, sex)
        floor = min(v[i][1] for i in used)
        metres = lambda p: (p[0] / 10, (p[1] - floor) / 10, p[2] / 10)  # MakeHuman works in decimetres
        positions = [round(c * SCALE) for i in used for c in metres(v[i])]
        assert max(abs(c) for c in positions) < 32768
        joints = {}
        for name, helper in JOINTS.items():
            points = [metres(v[i]) for i in groups[helper]]
            joints[name] = [round(sum(p[k] for p in points) / len(points), 4) for k in range(3)]
        figures[sex] = {"positions": positions, "joints": joints, "height": round(max(metres(v[i])[1] for i in used), 3)}

    pack = lambda fmt, values: base64.b64encode(struct.pack(f"<{len(values)}{fmt}", *values)).decode()
    male = figures["male"]["positions"]
    female = [f - m for f, m in zip(figures["female"]["positions"], male)]
    assert max(abs(d) for d in female) < 32768

    def joints(sex):
        return "{ " + ", ".join(f"{k}: [{', '.join(str(c) for c in v)}]" for k, v in figures[sex]["joints"].items()) + " }"

    target.write_text(
        f"""// Generated by scripts/build-figures.py from MakeHuman's base mesh and targets
// (CC0: https://github.com/makehumancommunity/makehuman). Don't edit: rebuild.
// The figure faces +z, its left side at +x, feet at y = 0, in metres; each
// joint is the left one (the figure is symmetric).

/** Integer steps per metre in the positions. */
export const SCALE = {SCALE};

/** {len(used)} vertices, {len(quads)} quads (MakeHuman's own), as little-endian uint16 vertex indices. */
export const QUADS = "{pack('H', [index[i] for quad in quads for i in quad])}";

/** The male figure's positions, little-endian int16 x, y, z per vertex. */
export const MALE = "{pack('h', male)}";

/** The female figure, as differences from the male, the same way. */
export const FEMALE_DELTA = "{pack('h', female)}";

export const JOINTS = {{
  male: {joints('male')},
  female: {joints('female')},
}} as const;

export const HEIGHTS = {{ male: {figures['male']['height']}, female: {figures['female']['height']} }} as const;
"""
    )
    print(f"{target}: {len(used)} vertices, {len(quads)} quads, {target.stat().st_size // 1024} KB")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(Path(sys.argv[1]), Path(sys.argv[2]))
